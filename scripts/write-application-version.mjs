import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const DEFAULT_OUTPUT_PATH = "src/lib/application-version.generated.ts";
const DEFAULT_PACKAGE_PATH = "package.json";

function parseArguments(argumentsList) {
    const options = {
        outputPath: DEFAULT_OUTPUT_PATH,
        packagePath: DEFAULT_PACKAGE_PATH,
        stage: false,
        timestamp: new Date().toISOString(),
    };

    for (let index = 0; index < argumentsList.length; index += 1) {
        const argument = argumentsList[index];

        if (argument === "--output") {
            options.outputPath = argumentsList[index + 1] ?? "";
            index += 1;
        } else if (argument === "--package") {
            options.packagePath = argumentsList[index + 1] ?? "";
            index += 1;
        } else if (argument === "--stage") {
            options.stage = true;
        } else if (argument === "--timestamp") {
            options.timestamp = argumentsList[index + 1] ?? "";
            index += 1;
        } else {
            throw new Error(`Unknown argument: ${argument}`);
        }
    }

    return options;
}

function assertTimestamp(timestamp) {
    const parsedTimestamp = new Date(timestamp);

    if (
        !Number.isFinite(parsedTimestamp.getTime()) ||
        parsedTimestamp.toISOString() !== timestamp
    ) {
        throw new Error("Application version must be an ISO 8601 UTC timestamp.");
    }
}

async function readReleaseTag(packagePath) {
    const packageJson = JSON.parse(await readFile(packagePath, "utf8"));
    const version = packageJson.version;

    if (
        packageJson.name !== "budgeted" ||
        typeof version !== "string" ||
        !/^(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)$/.test(version)
    ) {
        throw new Error(
            'The application package must be named "budgeted" and use a stable semantic version.',
        );
    }

    return `v${version}`;
}

function createSource(timestamp, releaseTag) {
    return [
        "// Generated by the pre-commit hook. Do not edit manually.",
        "export const GENERATED_APPLICATION_VERSION = {",
        `    buildTimestamp: ${JSON.stringify(timestamp)},`,
        `    releaseTag: ${JSON.stringify(releaseTag)},`,
        "} as const;",
        "",
    ].join("\n");
}

async function main() {
    const options = parseArguments(process.argv.slice(2));
    assertTimestamp(options.timestamp);

    const outputPath = resolve(process.cwd(), options.outputPath);
    const packagePath = resolve(process.cwd(), options.packagePath);
    const releaseTag = await readReleaseTag(packagePath);
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(
        outputPath,
        createSource(options.timestamp, releaseTag),
        "utf8",
    );

    if (options.stage) {
        execFileSync("git", ["add", "--", options.outputPath], {
            stdio: "inherit",
        });
    }
}

main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
});
